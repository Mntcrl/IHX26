#!/bin/bash
# Live interoperability check of the POV Swift client (XRPL_Galaxy/POV*.swift) against a running
# committee: compiles the app's own POV files for macOS with a small CLI, then submits
#   1. a real LiDAR scan (FLDP .fdepth + raw 256x192 confidence bytes)  -> expect PASS (anchored on XRPL)
#   2. a synthetic tilted plane (screen-like, all-high confidence)      -> expect REJECT planar_scene
# through exactly the iPhone path: POVClient.config/nodeKeysMatch/fetchT0 -> POVModel.buildRequest
# (POVDepth encode + Shamir split, Secure Enclave ECDSA, CryptoKit HPKE) -> POVClient.capture.
# The manifest says app "pov-sim/1" (not an iPhone). Images are generated bytes, never photos.
#
# Usage: tests/check-pov-parity.sh --print-pubkey
#        tests/check-pov-parity.sh <coordinator-url> <scan.fdepth> <scan.conf> [expected_rel_rms expected_frac]
# The harness key lives in this Mac's Secure Enclave (wrapped handle in the `pov-parity` user defaults);
# enroll its pubkey once on the operator machine: `cd pov/setup && npm run enroll -- <pubkey>`.
# Fixture: pov/testdata/scan_room.{fdepth,conf} of the POV repo (expected 0.3159 0.553).
set -euo pipefail
root="$(cd "$(dirname "$0")/.." && pwd)"
build="${POV_PARITY_BUILD:-/tmp/pov-parity}"
mkdir -p "$build"
cat > "$build/main.swift" <<'SWIFT'
import Foundation

func fail(_ message: String) -> Never {
    FileHandle.standardError.write(Data("FAIL: \(message)\n".utf8))
    exit(1)
}

func le32(_ value: UInt32) -> Data { withUnsafeBytes(of: value.littleEndian) { Data($0) } }

func randomBytes(_ count: Int) -> Data {
    var rng = SystemRandomNumberGenerator()
    return Data((0..<count).map { _ in UInt8.random(in: 0...255, using: &rng) })
}

/// Screen-like scene: plane tilted in x and y (1/z affine in pixels), ±0.4 % noise, all-high confidence.
func flatScene() -> (fdepth: Data, conf: Data) {
    var fdepth = Data("FLDP".utf8) + le32(256) + le32(192)
    for y in 0..<192 {
        for x in 0..<256 {
            let w = 1 / 0.6 + 0.0015 * Double(x - 128) + 0.001 * Double(y - 96)
            let z = Float32(1 / w * (1 + 0.004 * (2 * Double.random(in: 0..<1) - 1)))
            fdepth += le32(z.bitPattern)
        }
    }
    return (fdepth, Data(repeating: 2, count: 256 * 192))
}

let args = CommandLine.arguments
let key = try POVCrypto.deviceKey()
let pubkey = POVCrypto.pubkeyHex(key)
if args.count == 2 && args[1] == "--print-pubkey" {
    print(pubkey)
    exit(0)
}
guard args.count == 4 || args.count == 6, let base = URL(string: args[1]) else {
    fail("usage: pov-parity <coordinator-url> <scan.fdepth> <scan.conf> [expected_rel_rms expected_frac]")
}
let realFdepth = try Data(contentsOf: URL(fileURLWithPath: args[2]))
let realConf = try Data(contentsOf: URL(fileURLWithPath: args[3]))
let client = POVClient(base: base)
print("device pubkey \(pubkey) (Secure Enclave)")
let config = try await client.config()
guard try await POVClient.nodeKeysMatch(config) else { fail("node HPKE keys differ from the nodes' XRPL DIDs") }
print("committee \(config.committee_account): node HPKE keys match their XRPL DIDs")
guard let rpc = URL(string: config.xrpl_rpc) else { fail("bad xrpl_rpc") }

let work = FileManager.default.temporaryDirectory.appendingPathComponent("pov-parity-\(UUID().uuidString)")
try FileManager.default.createDirectory(at: work, withIntermediateDirectories: true)
let printer = JSONEncoder()
printer.outputFormatting = [.prettyPrinted, .sortedKeys, .withoutEscapingSlashes]

func submit(_ label: String, fdepth: Data, conf: Data) async throws -> Attempt {
    let image = Data("pov-parity \(label) \(UUID().uuidString)\n".utf8) + randomBytes(1024)
    let imageURL = work.appendingPathComponent("\(label).bin")
    let fdepthURL = work.appendingPathComponent("\(label).fdepth")
    let jsonURL = work.appendingPathComponent("\(label).json")
    try image.write(to: imageURL)
    try fdepth.write(to: fdepthURL)
    try JSONSerialization.data(withJSONObject: ["depth": ["confidence": ["data": conf.base64EncodedString()]]])
        .write(to: jsonURL)
    let t0 = try await POVClient.fetchT0(rpc: rpc)
    let request = try POVModel.buildRequest(jpegURL: imageURL, fdepthURL: fdepthURL, jsonURL: jsonURL,
                                            evidenceRoot: POVCrypto.sha256Hex(image + fdepth), t0: t0,
                                            config: config, app: "pov-sim/1")
    print("[\(label)] T0 \(t0.index) \(t0.hash), image_sha256 \(POVCrypto.sha256Hex(image)), submitting…")
    let attempt = try await client.capture(request)
    print("[\(label)] attempt:")
    print(String(decoding: try printer.encode(attempt), as: UTF8.self))
    return attempt
}

let room = try await submit("room", fdepth: realFdepth, conf: realConf)
let flat = flatScene()
let plane = try await submit("flat", fdepth: flat.fdepth, conf: flat.conf)
try? FileManager.default.removeItem(at: work)

var ok = true
if !room.passed { print("FAIL room: expected PASS, got \(room.verdict) \(room.reason ?? "")"); ok = false }
if args.count == 6 {
    let relRMS = room.rel_rms.map { String(format: "%.4f", $0) } ?? "nil"
    let frac = room.frac.map { String(format: "%.3f", $0) } ?? "nil"
    if relRMS != args[4] || frac != args[5] {
        print("FAIL room: rel_rms \(relRMS) frac \(frac), expected \(args[4]) \(args[5])"); ok = false
    } else {
        print("room rel_rms \(relRMS) frac \(frac) == expected (Rust cleartext)")
    }
}
if plane.verdict != "REJECT" || plane.reason != "planar_scene" {
    print("FAIL flat: expected REJECT planar_scene, got \(plane.verdict) \(plane.reason ?? "")"); ok = false
}
print(ok ? "POV PARITY OK" : "POV PARITY FAILED")
exit(ok ? 0 : 1)
SWIFT
swiftc -O -default-isolation MainActor \
    -enable-upcoming-feature NonisolatedNonsendingByDefault \
    -enable-upcoming-feature InferIsolatedConformances \
    -enable-upcoming-feature MemberImportVisibility \
    "$root"/XRPL_Galaxy/POV{Models,Crypto,Depth,Client,Model}.swift "$build/main.swift" -o "$build/pov-parity"
"$build/pov-parity" "$@"
