#!/usr/bin/env node
import { createHash } from 'node:crypto';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

function canonical(value) {
    if (typeof value === 'bigint') return String(value);
    if (Array.isArray(value)) return `[${value.map(canonical).join(',')}]`;
    if (value !== null && typeof value === 'object') {
        return `{${Object.keys(value).sort().map(key => `${JSON.stringify(key)}:${canonical(value[key])}`).join(',')}}`;
    }
    return JSON.stringify(value);
}

const fields = {
    lidar: 'd_min_mm d_max_mm conf_min area_min eps_log2 sep_log2 v_all_min v_c_min tile_valid_min tiles_cov_min plane_global_max_pct plane_central_max_pct tile_out_min nonplanar_tiles_min nonplanar_tiles_c_min strong_min_pct strong_tiles_min',
    rgb_depth: 'disc_pct grad_min_y disc_min edge_match_pct',
    temporal: 'occ_pm dcons_pm g_inf_y photo_tol_y t_usable_min occ_max_pct dok_min_pct inf_min pok_min_pct',
    quality: 'dt_min_us dt_max_us fx_min_q16 fx_max_q16 cx_min_q16 cx_max_q16 cy_min_q16 cy_max_q16 ortho_tol_q60',
    motion: 'baseline_min_um rot_max_q30 imu_min_samples imu_dt_max_us imu_cover_tol_us gyro_tol_urad m_cd grav_norm_tol_q40 grav_cos_milli acc_max_mg',
    windows: 'w_cap w_proof sel_offset',
};
const structural = {
    p: 1n << 32n, coefficient_bound: 1n << 36n, slots: 16n, central_slots: 8n,
    blocks_per_slot: 4n, global_hypotheses: 4n, central_hypotheses: 4n,
    temporal_quadrants: [0n, 3n], imu_max: 64n,
};

// The test-only profile is rendered in an isolated scratch directory by the
// differential runner. The CLI always reads and writes the production paths.
export function renderPolicy(source) {
    const policy = JSON.parse(source, (_key, value, context) => {
        if (typeof value !== 'number') return value;
        if (!/^-?(0|[1-9]\d*)$/.test(context?.source ?? '')) {
            throw new Error('expected integer JSON numbers (Node.js 22 or later required)');
        }
        return BigInt(context.source);
    });
    if (canonical(policy.structural) !== canonical(structural)) throw new Error('incompatible GalaxyPolicyV1m shape');
    const values = [];
    for (const [group, names] of Object.entries(fields)) {
        const keys = names.split(' ');
        const params = policy[group];
        if (!params || Object.keys(params).length !== keys.length) throw new Error(`invalid policy group ${group}`);
        for (const key of keys) {
            const value = params[key];
            if (key === 'm_cd') {
                const nonzero = entries => entries.filter(v => v !== 0n).length;
                if (!Array.isArray(value) || value.length !== 9 || value.some(v => ![-1n, 0n, 1n].includes(v)) ||
                    [0, 1, 2].some(i => nonzero(value.slice(3*i, 3*i+3)) !== 1 ||
                                        nonzero([value[i], value[i+3], value[i+6]]) !== 1)) {
                    throw new Error('m_cd must be a signed permutation');
                }
                values.push(`function POL_m_cd(row, col) { var entries[9] = [${value.join(', ')}]; return entries[3*row+col]; }`);
            } else {
                if (typeof value !== 'bigint' || value < 0n || value >= (1n << 64n)) {
                    throw new Error(`invalid uint64 policy constant ${group}.${key}`);
                }
                values.push(`function POL_${key}() { return ${value}; }`);
            }
        }
    }
    for (const [key, value] of Object.entries(policy.structural)) {
        if (Array.isArray(value)) {
            values.push(`function POL_${key}(i) { var entries[${value.length}] = [${value.join(', ')}]; return entries[i]; }`);
        } else {
            values.push(`function POL_${key}() { return ${value}; }`);
        }
    }
    // Valid vertices must have nonzero depths and area, for the exact Den in §8.2.
    const { d_min_mm, d_max_mm, area_min, eps_log2, sep_log2 } = policy.lidar;
    if (d_min_mm < 1n || d_min_mm > d_max_mm || d_max_mm >= 8192n || area_min < 1n ||
        eps_log2 > sep_log2 || sep_log2 > 36n) throw new Error('policy violates LiDAR arithmetic bounds');
    if (policy.temporal.occ_pm > 1000n) throw new Error('occ_pm exceeds 1000');

    // Same canonical bytes as galaxy-protocol (cross-checked against
    // test-vectors/protocol/policy.json); policy_id per spec §3.
    const canonicalBytes = Buffer.from(canonical(policy), 'utf8');
    const policySha256 = createHash('sha256').update(canonicalBytes).digest('hex');
    const policyId = createHash('sha256').update(Buffer.from('GALAXY/POLICY/v1\0', 'utf8')).update(canonicalBytes).digest('hex');
    return {
        'policy_v1m.circom': '// Generated by scripts/circuit-gen-policy.mjs; do not edit.\npragma circom 2.2.2;\n\n' + values.join('\n') + '\n',
        'policy_v1m.manifest.json': JSON.stringify({
            generator: 'scripts/circuit-gen-policy.mjs',
            name: policy.name,
            policy_canonical_sha256: policySha256,
            policy_id: policyId,
        }, null, 2) + '\n',
    };
}

if (import.meta.main) {
    const source = new URL('../policies/galaxy-pc-v1m.json', import.meta.url);
    const output = new URL('../circuits/physical-consistency/generated/', import.meta.url);
    const files = renderPolicy(readFileSync(source, 'utf8'));
    if (process.argv.length === 3 && process.argv[2] === '--check') {
        for (const [name, expected] of Object.entries(files)) {
            if (readFileSync(new URL(name, output), 'utf8') !== expected) throw new Error(`stale generated file: ${name}`);
        }
    } else {
        if (process.argv.length !== 2) throw new Error('usage: node scripts/circuit-gen-policy.mjs [--check]');
        mkdirSync(fileURLToPath(output), { recursive: true });
        for (const [name, data] of Object.entries(files)) writeFileSync(new URL(name, output), data);
    }
    const manifest = JSON.parse(files['policy_v1m.manifest.json']);
    console.log(`${manifest.name} policy_id: ${manifest.policy_id} (canonical SHA-256 ${manifest.policy_canonical_sha256})`);
}
